#!/usr/bin/env python3
"""Generate Cisco IOS switch configurations from a JSON description.

Describe a switch once (VLANs, access ports, trunks, management) and get a
complete, hardened configuration: SSH only, port security, BPDU guard,
DHCP snooping, unused ports shut down in a black-hole VLAN.

Examples:
    python3 genconfig.py examples/hotel-floor1.json
    python3 genconfig.py examples/*.json --out configs/
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import re
import sys
from pathlib import Path

RANGE_RE = re.compile(r"^(?P<prefix>[A-Za-z]+[\d/]*/)(?P<a>\d+)(?:-(?P<b>\d+))?$")


class ConfigError(ValueError):
    pass


def expand_ports(spec: str) -> list[str]:
    """'Gi1/0/1-3, Gi1/0/10' -> ['Gi1/0/1', 'Gi1/0/2', 'Gi1/0/3', 'Gi1/0/10']"""
    out = []
    for part in (p.strip() for p in spec.split(",")):
        if not part:
            continue
        m = RANGE_RE.match(part)
        if not m:
            raise ConfigError(f"bad interface '{part}' (expected e.g. Gi1/0/1 or Gi1/0/1-24)")
        a = int(m["a"])
        b = int(m["b"] or a)
        if b < a:
            raise ConfigError(f"bad range '{part}'")
        out += [f"{m['prefix']}{n}" for n in range(a, b + 1)]
    return out


def ios_range(spec: str) -> str:
    """'Gi1/0/1-6,Gi1/0/10' -> 'Gi1/0/1 - 6 , Gi1/0/10' (the spacing IOS expects)"""
    return " , ".join(re.sub(r"(\d+)-(\d+)$", r"\1 - \2", p.strip()) for p in spec.split(",") if p.strip())


def validate(cfg: dict) -> list[str]:
    """Return a list of problems. An empty list means the design is OK."""
    problems = []
    for key in ("hostname", "vlans", "ports"):
        if key not in cfg:
            problems.append(f"missing '{key}'")
    if problems:
        return problems

    vlan_ids = set()
    for v in cfg["vlans"]:
        if not 1 < v["id"] < 4095 or 1002 <= v["id"] <= 1005:
            problems.append(f"VLAN {v['id']} is reserved or out of range")
        if v["id"] in vlan_ids:
            problems.append(f"VLAN {v['id']} defined twice")
        vlan_ids.add(v["id"])

    seen: dict[str, str] = {}
    for group in cfg["ports"]:
        try:
            ifaces = expand_ports(group["interfaces"])
        except ConfigError as e:
            problems.append(str(e))
            continue
        for i in ifaces:
            if i in seen:
                problems.append(f"{i} used by both '{seen[i]}' and '{group.get('description', '?')}'")
            seen[i] = group.get("description", "?")
        mode = group.get("mode", "access")
        if mode == "access" and group.get("vlan") not in vlan_ids:
            problems.append(f"{group['interfaces']}: access VLAN {group.get('vlan')} is not defined")
        if mode == "access" and group.get("voice_vlan") and group["voice_vlan"] not in vlan_ids:
            problems.append(f"{group['interfaces']}: voice VLAN {group['voice_vlan']} is not defined")
        if mode == "trunk":
            for vid in group.get("allowed", []):
                if vid not in vlan_ids:
                    problems.append(f"{group['interfaces']}: trunk allows undefined VLAN {vid}")
            if group.get("native") in vlan_ids and any(
                    v["id"] == group["native"] and v.get("users") for v in cfg["vlans"]):
                problems.append(f"{group['interfaces']}: native VLAN carries user traffic (VLAN hopping risk)")

    mgmt = cfg.get("management")
    if mgmt:
        if mgmt["vlan"] not in vlan_ids:
            problems.append(f"management VLAN {mgmt['vlan']} is not defined")
        try:
            iface = ipaddress.IPv4Interface(mgmt["ip"])
            gw = ipaddress.IPv4Address(mgmt["gateway"])
            if gw not in iface.network:
                problems.append(f"gateway {gw} is not in management subnet {iface.network}")
        except (ValueError, KeyError) as e:
            problems.append(f"management: {e}")
    return problems


def render(cfg: dict) -> str:
    problems = validate(cfg)
    if problems:
        raise ConfigError("; ".join(problems))

    L: list[str] = []
    add = L.append
    blackhole = cfg.get("unused_vlan", 999)
    domain = cfg.get("domain", "lan.local")

    add("! Generated by genconfig.py. Review before pasting into a live switch.")
    add("!")
    add(f"hostname {cfg['hostname']}")
    add("service password-encryption")
    add("service timestamps log datetime msec localtime")
    add("no ip http server")
    add("no ip http secure-server")
    add("no ip domain-lookup")
    add(f"ip domain-name {domain}")
    add("!")
    if cfg.get("banner"):
        add(f"banner motd ^{cfg['banner']}^")
        add("!")

    add("! ---- VLANs ----")
    for v in sorted(cfg["vlans"], key=lambda v: v["id"]):
        add(f"vlan {v['id']}")
        add(f" name {v['name'].replace(' ', '_')}")
    add(f"vlan {blackhole}")
    add(" name UNUSED_BLACKHOLE")
    add("!")
    add("spanning-tree mode rapid-pvst")
    add("spanning-tree portfast bpduguard default")
    add("!")

    snoop_vlans = [str(v["id"]) for v in cfg["vlans"] if v.get("users")]
    trusted: list[str] = []

    add("! ---- Interfaces ----")
    used: set[str] = set()
    for group in cfg["ports"]:
        ifaces = expand_ports(group["interfaces"])
        used.update(ifaces)
        mode = group.get("mode", "access")
        add(f"interface range {ios_range(group['interfaces'])}" if len(ifaces) > 1 else f"interface {ifaces[0]}")
        if group.get("description"):
            add(f" description {group['description']}")
        if mode == "trunk":
            trusted += ifaces
            add(" switchport mode trunk")
            add(" switchport nonegotiate")
            if group.get("native"):
                add(f" switchport trunk native vlan {group['native']}")
            if group.get("allowed"):
                add(f" switchport trunk allowed vlan {','.join(map(str, group['allowed']))}")
            add(" ip dhcp snooping trust")
        else:
            add(" switchport mode access")
            add(" switchport nonegotiate")
            add(f" switchport access vlan {group['vlan']}")
            if group.get("voice_vlan"):
                add(f" switchport voice vlan {group['voice_vlan']}")
            add(" spanning-tree portfast")
            ps = group.get("port_security")
            if ps:
                add(" switchport port-security")
                add(f" switchport port-security maximum {ps.get('max', 2)}")
                add(f" switchport port-security violation {ps.get('violation', 'restrict')}")
                if ps.get("sticky", True):
                    add(" switchport port-security mac-address sticky")
            if group.get("storm_control"):
                add(" storm-control broadcast level 5.00")
            if group.get("vlan") and str(group["vlan"]) in snoop_vlans:
                add(" ip dhcp snooping limit rate 15")
        add(" no shutdown")
        add("!")

    unused = [i for i in expand_ports(cfg["switch_ports"]) if i not in used] if cfg.get("switch_ports") else []
    if unused:
        add("! ---- Unused ports: shut down and parked in the black-hole VLAN ----")
        for i in unused:
            add(f"interface {i}")
            add(" description UNUSED")
            add(" switchport mode access")
            add(f" switchport access vlan {blackhole}")
            add(" shutdown")
        add("!")

    if snoop_vlans:
        add("! ---- DHCP snooping (blocks rogue DHCP servers) ----")
        add("ip dhcp snooping")
        add(f"ip dhcp snooping vlan {','.join(snoop_vlans)}")
        add("no ip dhcp snooping information option")
        add("!")

    mgmt = cfg.get("management")
    if mgmt:
        iface = ipaddress.IPv4Interface(mgmt["ip"])
        add("! ---- Management ----")
        add(f"interface vlan {mgmt['vlan']}")
        add(" description MANAGEMENT")
        add(f" ip address {iface.ip} {iface.netmask}")
        add(" no shutdown")
        add("!")
        add(f"ip default-gateway {mgmt['gateway']}")
        if mgmt.get("allowed_admin_subnet"):
            net = ipaddress.IPv4Network(mgmt["allowed_admin_subnet"])
            add("ip access-list standard MGMT-ONLY")
            add(f" permit {net.network_address} {net.hostmask}")
            add(" deny any log")
        for srv in mgmt.get("ntp", []):
            add(f"ntp server {srv}")
        if mgmt.get("syslog"):
            add(f"logging host {mgmt['syslog']}")
            add("logging trap warnings")
        add("!")

    add("! ---- Secure remote access ----")
    add("crypto key generate rsa modulus 2048")
    add("ip ssh version 2")
    add("ip ssh time-out 60")
    add("ip ssh authentication-retries 3")
    add("login block-for 120 attempts 5 within 60")
    add("username admin privilege 15 secret CHANGE_ME")
    add("enable secret CHANGE_ME")
    add("line con 0")
    add(" login local")
    add(" exec-timeout 10 0")
    add(" logging synchronous")
    add("line vty 0 15")
    add(" login local")
    add(" transport input ssh")
    add(" exec-timeout 10 0")
    if mgmt and mgmt.get("allowed_admin_subnet"):
        add(" access-class MGMT-ONLY in")
    add("!")
    add("end")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Cisco IOS switch config generator")
    ap.add_argument("files", nargs="+", help="JSON switch descriptions")
    ap.add_argument("--out", help="folder to write <hostname>.cfg files into (default: print)")
    ap.add_argument("--check", action="store_true", help="only validate, don't print configs")
    args = ap.parse_args(argv)

    status = 0
    for path in args.files:
        cfg = json.loads(Path(path).read_text(encoding="utf-8"))
        problems = validate(cfg)
        if problems:
            status = 1
            print(f"{path}: {len(problems)} problem(s)", file=sys.stderr)
            for p in problems:
                print(f"  - {p}", file=sys.stderr)
            continue
        if args.check:
            print(f"{path}: OK")
            continue
        text = render(cfg)
        if args.out:
            out = Path(args.out)
            out.mkdir(parents=True, exist_ok=True)
            target = out / f"{cfg['hostname']}.cfg"
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target} ({text.count(chr(10))} lines)")
        else:
            print(text)
    return status


if __name__ == "__main__":
    sys.exit(main())
